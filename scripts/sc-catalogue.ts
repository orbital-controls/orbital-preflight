/**
 * Builds `src/lib/orbital-preflight/sims/star-citizen/defaults.ts` from the game's own
 * files: `Data\Libs\Config\defaultProfile.xml` (the default binds) and the English
 * `Data\Localization\english\global.ini` (the names the keybinding screen shows), both
 * unpacked from Data.p4k with unp4k or unforge.
 *
 *   node scripts/sc-catalogue.ts <defaultProfile.xml> <global.ini> <game version>
 *
 * The defaults in use are checked in as data/star-citizen/defaultProfile.xml, with the
 * build_manifest.json that names their game build. Replace both after a patch.
 *
 * Only action maps the keybinding screen lists (those with a `UICategory`) and actions it
 * labels (`UILabel`) are kept; debug, spectator and dev-camera maps aren't. Run it again
 * with a newer game's files to follow a patch.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { attribute, parseXml, type XmlElement } from '../src/lib/orbital-preflight/xml.ts';

const OUT = 'src/lib/orbital-preflight/sims/star-citizen/defaults.ts';

/** Maps with a UICategory that aren't about playing: the spectator mode for e-sports. */
const SKIP_MAPS = new Set(['spectator']);

const DEVICES = ['keyboard', 'mouse', 'joystick', 'gamepad'] as const;

function readIni(path: string): Map<string, string> {
	const strings = new Map<string, string>();
	for (const line of readFileSync(path, 'utf8')
		.replace(/^\uFEFF/, '')
		.split(/\r?\n/)) {
		const eq = line.indexOf('=');
		if (eq > 0) strings.set(line.slice(0, eq).replace(/,P$/, ''), line.slice(eq + 1).trim());
	}
	return strings;
}

/** The first default input an action gives a device: an attribute or nested inputdata. */
function defaultInput(action: XmlElement, device: (typeof DEVICES)[number]): string {
	const value = attribute(action, device)?.value.trim();
	if (value && value !== '0' && value !== '1') return value;
	const nested = action.children.find((c) => c.name === device);
	const first = nested?.children.find((c) => c.name === 'inputdata');
	return first ? (attribute(first, 'input')?.value.trim() ?? '') : '';
}

function main([profilePath, iniPath, version]: string[]) {
	if (!profilePath || !iniPath || !version) {
		throw new Error(
			'Usage: node scripts/sc-catalogue.ts <defaultProfile.xml> <global.ini> <version>'
		);
	}
	const strings = readIni(iniPath);
	const text = (key: string | undefined) => (key ? (strings.get(key.replace(/^@/, '')) ?? '') : '');
	const root = parseXml(readFileSync(profilePath, 'utf8'));
	const maps: unknown[] = [];
	let count = 0;

	for (const map of root.children.filter((c) => c.name === 'actionmap')) {
		const name = attribute(map, 'name')!.value;
		if (!attribute(map, 'UICategory')?.value || SKIP_MAPS.has(name)) continue;
		const actions: unknown[] = [];
		for (const action of map.children.filter((c) => c.name === 'action')) {
			const label = text(attribute(action, 'UILabel')?.value);
			if (!label) continue;
			const [kb, mouse, js, gp] = DEVICES.map((d) => defaultInput(action, d));
			const mode = attribute(action, 'activationMode')?.value ?? '';
			const axis = attribute(action, 'optionGroup') ? 1 : 0;
			actions.push([attribute(action, 'name')!.value, label, kb, mouse, js, gp, mode, axis]);
		}
		if (!actions.length) continue;
		count += actions.length;
		maps.push({ map: name, label: text(attribute(map, 'UILabel')?.value) || name, actions });
	}

	const source = `/**
 * GENERATED by scripts/sc-catalogue.ts from Star Citizen ${version}'s defaultProfile.xml
 * and English global.ini. Don't edit by hand: run the script on a newer game's files.
 *
 * Each action: [name, label, keyboard, mouse, joystick, gamepad, activationMode, axis].
 * The four inputs are the game's defaults for that device ('' for none), in the file's
 * own spelling (\`lalt+n\`, \`mouse1\`, \`button3\`, \`thumblx\`).
 */

export const GAME_VERSION = ${JSON.stringify(version)};

export type DefaultAction = [
	name: string,
	label: string,
	keyboard: string,
	mouse: string,
	joystick: string,
	gamepad: string,
	activationMode: string,
	axis: 0 | 1
];

export interface DefaultMap {
	map: string;
	label: string;
	actions: DefaultAction[];
}

export const DEFAULT_MAPS: DefaultMap[] = ${JSON.stringify(maps)};
`;
	writeFileSync(OUT, source);
	execFileSync('pnpm', ['exec', 'prettier', '--write', OUT], { stdio: 'inherit' });
	console.log(`${maps.length} action maps, ${count} actions → ${OUT}`);
}

main(process.argv.slice(2));
